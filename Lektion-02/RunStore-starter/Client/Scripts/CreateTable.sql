CREATE TABLE IF NOT EXISTS Customers(
    id VARCHAR(128) PRIMARY KEY NOT NULL,
    firstName TEXT VARCHAR(20) NOT NULL,
    lastName TEXT VARCHAR(30) NOT NULL,
    email TEXT VARCHAR(128) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS Products(
    id VARCHAR(128) PRIMARY KEY NOT NULL,
    description TEXT VARCHAR(128),
    imageUrl TEXT VARCHAR(128),
    itemNumber INTEGER UNIQUE NOT NULL,
    name TEXT VARCHAR(128) UNIQUE NOT NULL,
    price INTEGER NOT NULL,
    supplierName TEXT(128) NOT NULL
)